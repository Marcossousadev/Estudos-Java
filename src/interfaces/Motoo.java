package interfaces;
// uma interface é um contrato que a classe deve seguir
// quais métodos a classe deve seguir
// é uma casca
// dentro de uma interface, não temos implementação, apenas assinatura
// pois ela não pode ter implementação
// essa é a diferença de uma interface para uma classe abstrata, a classe abstrata pode ter implementação em um método
public interface Motoo {
    void acelerar();
    void freiar();
    void parar();
}
